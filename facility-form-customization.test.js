import assert from "node:assert/strict";
import { test } from "node:test";
import { readFileSync } from "node:fs";
import {
    DEFAULT_PROFILE_FIELDS,
    FORM_CUSTOMIZATION_SECTIONS,
    getFacilityProfileFieldValue,
    getFacilityProfileFields,
    normalizeFacilityFormCustomization
} from "./facility-form-customization.js";

test("unconfigured facilities keep the original form and have no custom fields", () => {
    assert.deepEqual(normalizeFacilityFormCustomization(undefined), { hiddenSections: [], customFields: [] });
});

test("emergency contact and medical history fields are available to every facility", () => {
    assert.deepEqual(DEFAULT_PROFILE_FIELDS.map(({ id, label, type, familyVisible }) => ({ id, label, type, familyVisible })), [
        { id: "emergency-contact", label: "緊急連絡先", type: "textarea", familyVisible: false },
        { id: "medical-history", label: "持病", type: "textarea", familyVisible: false },
        { id: "past-medical-history", label: "既往歴", type: "textarea", familyVisible: false }
    ]);
    assert.deepEqual(getFacilityProfileFields(), DEFAULT_PROFILE_FIELDS);
});

test("default profile fields replace same-label facility fields without losing saved values", () => {
    const configuredFields = [
        { id: "legacy-contact", label: "緊急連絡先", type: "text" },
        { id: "legacy-condition", label: "持病", type: "textarea" },
        { id: "support-note", label: "支援メモ", type: "textarea" }
    ];
    const profileFields = getFacilityProfileFields(configuredFields);
    const savedData = { customProfileFields: { "legacy-contact": "家族 090-0000-0000", "legacy-condition": "ぜんそく" } };
    assert.deepEqual(profileFields.map(field => field.id), ["emergency-contact", "medical-history", "past-medical-history", "support-note"]);
    assert.equal(getFacilityProfileFieldValue(savedData, profileFields[0], configuredFields), "家族 090-0000-0000");
    assert.equal(getFacilityProfileFieldValue(savedData, profileFields[1], configuredFields), "ぜんそく");
});

test("customization accepts only known sections and valid bounded custom fields", () => {
    const result = normalizeFacilityFormCustomization({
        hiddenSections: ["careJournalArea", "unknown", "careJournalArea"],
        customFields: [
            { id: "mood", label: "  今日の気分  ", type: "select", familyVisible: true },
            { id: "support-note", label: "支援メモ", type: "textarea", familyVisible: true },
            { id: "invalid id", label: "不正ID", type: "text" },
            { id: "blank", label: "   ", type: "text" }
        ]
    });
    assert.deepEqual(result.hiddenSections, ["careJournalArea"]);
    assert.deepEqual(result.customFields, [
        { id: "mood", label: "今日の気分", type: "text", familyVisible: true },
        { id: "support-note", label: "支援メモ", type: "textarea", familyVisible: true }
    ]);
});

test("customization accepts field-prefixed UUID identifiers generated by the admin panel", () => {
    const generatedId = "field-123e4567-e89b-12d3-a456-426614174000";
    assert.equal(generatedId.length, 42);
    assert.deepEqual(
        normalizeFacilityFormCustomization({ customFields: [{ id: generatedId, label: "緊急連絡先", type: "text" }] }).customFields,
        [{ id: generatedId, label: "緊急連絡先", type: "text", familyVisible: false }]
    );
});

test("medical history label is renamed without changing saved field identifiers or chronic conditions", () => {
    const { customFields } = normalizeFacilityFormCustomization({
        customFields: [{ id: "past-history", label: "持病歴", type: "textarea", familyVisible: false }]
    });
    assert.deepEqual(customFields, [
        { id: "past-history", label: "既往歴", type: "textarea", familyVisible: false }
    ]);
    const fields = getFacilityProfileFields(customFields);
    assert.equal(fields.find(field => field.id === "medical-history").label, "持病");
    // 施設独自の「既往歴」は標準の既往歴欄にまとめられ、保存済みの内容はそのまま表示される
    assert.equal(fields.filter(field => field.label === "既往歴").length, 1);
    assert.equal(getFacilityProfileFieldValue({
        customProfileFields: { "past-history": "急性大腸炎" }
    }, fields.find(field => field.id === "past-medical-history"), customFields), "急性大腸炎");
});

test("custom field definitions are limited to twenty", () => {
    const customFields = Array.from({ length: 25 }, (_, index) => ({
        id: `field-${index}`, label: `項目${index}`, type: "text"
    }));
    assert.equal(normalizeFacilityFormCustomization({ customFields }).customFields.length, 20);
    assert.equal(FORM_CUSTOMIZATION_SECTIONS.length > 0, true);
});

test("every customizable standard section exists in the facility input page", () => {
    const inputPage = readFileSync(new URL("./index.html", import.meta.url), "utf8");
    for (const section of FORM_CUSTOMIZATION_SECTIONS) {
        assert.ok(inputPage.includes(`id="${section.id}"`), `missing input section ${section.id}`);
    }
});